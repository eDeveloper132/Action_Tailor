/**
 * HTML Sanitization Utility to prevent Cross-Site Scripting (XSS)
 * Escapes dangerous HTML entities before string interpolation.
 */
export function escapeHtml(str: any): string {
  if (str === null || str === undefined) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

